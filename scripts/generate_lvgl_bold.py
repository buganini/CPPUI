#!/usr/bin/env python3
"""Regenerate desktop bold fonts with lv_font_conv 1.5.3 (not needed to build)."""

import argparse
from pathlib import Path
import re
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--lvgl-source", required=True, type=Path)
parser.add_argument("--converter", default="lv_font_conv")
args = parser.parse_args()
version = subprocess.check_output([args.converter, "--version"], text=True).strip()
if version != "1.5.3":
    parser.error(f"expected lv_font_conv 1.5.3, found {version}")
sdk = args.lvgl_source.resolve()
output = Path(__file__).resolve().parents[1] / "cppui/lvgl/fonts"
font = sdk / "tests/src/test_files/fonts/Montserrat-Bold.ttf"

for size in (14, 28):
    name = f"cppui_font_montserrat_bold_{size}"
    with tempfile.TemporaryDirectory() as temporary:
        subprocess.run([
            args.converter, "--size", str(size), "--bpp", "4", "--format", "lvgl",
            "--font", str(font), "--range", "0x20-0x7f,0xb0,0x2022", "--symbols", "×·–→",
            "--no-compress", "--no-prefilter", "--lv-font-name", name, "-o", name + ".c",
        ], cwd=temporary, check=True)
        code = (Path(temporary) / (name + ".c")).read_text()
    code = re.sub(r" \* Opts:.*", " * Generated by scripts/generate_lvgl_bold.py with lv_font_conv 1.5.3.\n"
                  " * Derived from Montserrat Bold; see OFL.txt for copyright and license.", code)
    # Keep the same line metrics when switching weight, and use the regular
    # font for the SDK's icon glyphs and any configured Unicode fallbacks.
    parent = (sdk / f"src/font/lv_font_montserrat_{size}.c").read_text()
    for metric in ("line_height", "base_line"):
        value = re.search(r"\." + metric + r" = (-?\d+)", parent).group(1)
        code = re.sub(r"\." + metric + r" = -?\d+", f".{metric} = {value}", code)
    code = code.replace("    .fallback = NULL,", f"    .fallback = &lv_font_montserrat_{size},")
    code = code.replace("    .dsc = &font_dsc,", "    .static_bitmap = 1,\n    .dsc = &font_dsc,")
    (output / (name + ".c")).write_text(code.rstrip() + "\n")
