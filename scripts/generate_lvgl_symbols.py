#!/usr/bin/env python3
"""Regenerate the desktop symbol fonts with lv_font_conv 1.5.3 (not needed to build)."""

import argparse
from pathlib import Path
import re
import subprocess
import tempfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--lvgl-source", required=True, type=Path)
parser.add_argument("--converter", default="lv_font_conv")
args = parser.parse_args()
version = subprocess.check_output([args.converter, "--version"], text=True).strip()
if version != "1.5.3":
    parser.error(f"expected lv_font_conv 1.5.3, found {version}")
sdk = args.lvgl_source.resolve()
output = Path(__file__).resolve().parents[1] / "cppui/lvgl/fonts"
output.mkdir(parents=True, exist_ok=True)
font = sdk / "scripts/generators/built_in_font/Montserrat-Medium.ttf"

for size in (14, 28):
    name = f"cppui_font_symbols_{size}"
    with tempfile.TemporaryDirectory() as temporary:
        subprocess.run([
            args.converter, "--size", str(size), "--bpp", "4", "--format", "lvgl",
            "--font", str(font), "--symbols", "×·–→", "--no-compress", "--no-prefilter",
            "--no-kerning", "--lv-font-name", name, "-o", name + ".c",
        ], cwd=temporary, check=True)
        code = (Path(temporary) / (name + ".c")).read_text()
    code = re.sub(r" \* Opts:.*", " * Generated by scripts/generate_lvgl_symbols.py with lv_font_conv 1.5.3.\n"
                  " * Derived from Montserrat; see OFL.txt for copyright and license.", code)
    # A subset's own bounds are shorter than the parent font's. Keep the same
    # baseline/line metrics, including when LVGL draws a resolved fallback alone.
    parent = (sdk / f"src/font/lv_font_montserrat_{size}.c").read_text()
    for metric in ("line_height", "base_line"):
        value = re.search(r"\." + metric + r" = (-?\d+)", parent).group(1)
        code = re.sub(r"\." + metric + r" = -?\d+", f".{metric} = {value}", code)
    code = code.replace("    .dsc = &font_dsc,", "    .static_bitmap = 1,\n    .dsc = &font_dsc,")
    (output / (name + ".c")).write_text(code.rstrip() + "\n")

license_file = sdk / "scripts/generators/built_in_font/font_license/Montserrat/OFL.txt"
(output / "OFL.txt").write_text("\n".join(line.rstrip() for line in license_file.read_text().splitlines()) + "\n")
